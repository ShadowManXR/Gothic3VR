"""Install/uninstall the real Setup EXE against a private native-DLL fixture.

Never launches Gothic 3. Stops if an earlier managed VR setup is registered.
"""
from pathlib import Path
import hashlib
import json
import os
import shutil
import subprocess
import uuid
import winreg

ROOT=Path(__file__).resolve().parents[1]
PACKAGE=ROOT.parents[1]/'outputs/Gothic3VR-0.23.119'
WORK=ROOT.parent/'release-0.23.119'/('setup-smoke-'+uuid.uuid4().hex[:8])
GAME=WORK/'Gothic 3 ș'
LIVE=Path(r'D:\SteamLibrary\steamapps\common\Gothic 3')
METADATA=Path(os.environ['LOCALAPPDATA'])/'Gothic3VR/Setup'
key=r'Software\Microsoft\Windows\CurrentVersion\Uninstall\{872AAFD4-B6F2-4BE7-812F-2D5B19A22425}_is1'
for hive in (winreg.HKEY_CURRENT_USER,winreg.HKEY_LOCAL_MACHINE):
    for view in (winreg.KEY_WOW64_32KEY,winreg.KEY_WOW64_64KEY):
        try:
            k=winreg.OpenKey(hive,key,0,winreg.KEY_READ|view);k.Close();raise RuntimeError('A managed VR install already exists; do not replace its registration during smoke testing')
        except FileNotFoundError:pass
assert not METADATA.exists() or not any(METADATA.iterdir()),'Do not overwrite prior setup metadata'
GAME.mkdir(parents=True)
(GAME/'Gothic3.exe').write_text('Test fixture only. Never executable.')
manifest=json.loads((PACKAGE/'G3VR.Payload.json').read_text())
for f in manifest['Required']:
    dest=GAME/f['Path'];dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(LIVE/f['Path'],dest)
(GAME/'Ini').mkdir()
(GAME/'Ini/ge3.ini').write_text('[Game]\nQuickLoot=false\n[Engine.Setup]\nEntity.ROI=4000\n')
shutil.copy2(GAME/'Ini/ge3.ini',WORK/'native-before.ini')
(GAME/'saves').mkdir();(GAME/'saves/test.sav').write_text('untouched')
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest().upper()
def execute(exe,args):
    result=subprocess.run([str(exe)]+args,creationflags=subprocess.CREATE_NO_WINDOW,timeout=150)
    assert result.returncode==0,f'Installer exit {result.returncode}; inspect {WORK}'
execute(PACKAGE/'Gothic3VR-0.23.119-Setup.exe',['/VERYSILENT','/SUPPRESSMSGBOXES','/NORESTART','/NOICONS','/CURRENTUSER',f'/DIR={GAME}','/COMPONENTS=core,graphics,branding,music',f'/LOG={WORK / "setup.log"}'])
for f in manifest['Files']:assert sha(GAME/f['Path'])==f['Sha'],f['Path']
assert (METADATA/'START-HERE.html').exists()
assert not any(p.name.endswith('.pdb') or p.suffix=='.jsonl' for p in GAME.rglob('*'))
print('PASS Real Setup installs every selected component with exact manifest hashes',flush=True)
# Use the registered uninstaller generated by this exact setup, not a guessed path.
with winreg.OpenKey(winreg.HKEY_CURRENT_USER,key) as k:
    uninstall=winreg.QueryValueEx(k,'UninstallString')[0].strip('"')
execute(Path(uninstall),['/VERYSILENT','/SUPPRESSMSGBOXES','/NORESTART',f'/LOG={WORK / "uninstall.log"}'])
for f in manifest['Files']:
    target=GAME/f['Path'];assert target.exists()==(f['Policy']=='if-missing'),f['Path']
for f in manifest['Required']:assert sha(GAME/f['Path'])==f['Sha']
assert (GAME/'saves/test.sav').read_text()=='untouched'
try:winreg.OpenKey(winreg.HKEY_CURRENT_USER,key);raise AssertionError('Uninstaller registration remained')
except FileNotFoundError:pass
assert not (METADATA/'Deploy.ps1').exists()
print('PASS Real uninstaller preserves native modules, saves and calibration and removes setup registration',flush=True)
(WORK/'results.json').write_text(json.dumps(dict(SetupSha=sha(PACKAGE/'Gothic3VR-0.23.119-Setup.exe'),Passed=True,Game=str(GAME),Published=False),indent=2))
print('RESULT',WORK)
