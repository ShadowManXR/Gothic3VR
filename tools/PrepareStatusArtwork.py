"""Pack imagegen artwork into fixed, premultiplied HUD texels.

Mechanical size/format conversion only: preserve artwork and generated alpha.
No image synthesis, background removal, hue replacement or drawn substitutes.
Runtime needs no image decoder, resource lookup, extra GPU layer or disk I/O.
"""
from pathlib import Path
import hashlib
import json
import struct
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/status-icons'
SIZE = 128


def main():
    entries = []
    header = ['// Generated by tools/PrepareStatusArtwork.py. Do not edit.',
              '#pragma once', '#include <cstdint>',
              'namespace diagnostic::artwork {',
              f'inline constexpr unsigned StatusIconPixels={SIZE};']
    previews = []
    for name in ('sneak', 'parry', 'kill'):
        path = ASSETS / 'source' / (name + '.png')
        with Image.open(path) as original:
            if original.mode != 'RGBA' or original.getchannel('A').getextrema()[0] != 0:
                raise ValueError(f'{name}: generated artwork must retain transparent alpha')
            # Fit the complete original canvas, preserving aspect and all alpha.
            # Pillow's RGBA resampling interpolates in premultiplied alpha space.
            image = original.copy()
            image.thumbnail((SIZE-8, SIZE-8), Image.Resampling.LANCZOS)
            canvas = Image.new('RGBA', (SIZE, SIZE))
            canvas.paste(image, ((SIZE-image.width)//2, (SIZE-image.height)//2))
        canvas.save(ASSETS / (name + '.png'))
        previews.append(canvas)
        values = []
        for r, g, b, alpha in struct.iter_unpack('4B', canvas.tobytes()):
            a = alpha*239//255  # same maximum opacity as the previous HUD symbols
            values.append((a << 24) | ((r*a//255) << 16) | ((g*a//255) << 8) | (b*a//255))
        header.append(f'inline constexpr uint32_t {name.capitalize()}[{SIZE*SIZE}]{{')
        for offset in range(0, len(values), 8):
            header.append('    ' + ','.join(f'0x{v:08x}u' for v in values[offset:offset+8]) + ',')
        header.append('};')
        entries.append(dict(name=name, source_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                            source_size=original.size, output_pixels=[SIZE,SIZE],
                            png_sha256=hashlib.sha256((ASSETS/(name+'.png')).read_bytes()).hexdigest(),
                            visible_pixels=sum(bool(v>>24) for v in values)))
    header.extend(['inline uint32_t const* Status(int status){',
                   '    return status==1?Sneak:status==2?Kill:status==4?Parry:nullptr;',
                   '}', '}'])
    (ROOT/'src/WorldStatusArtwork.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
    (ASSETS/'manifest.json').write_text(json.dumps(dict(generator='built-in image_gen',
        format='128x128 BGRA premultiplied alpha, maximum alpha 239; compiled into plugin',
        entries=entries),indent=2)+'\n',encoding='utf-8')
    # QA contact sheet: exact final PNGs over two representative HUD backgrounds.
    preview = Image.new('RGBA', (SIZE*3, SIZE*2), (25,21,17,255))
    for row, color in enumerate(((25,21,17,255),(135,124,102,255))):
        for col, canvas in enumerate(previews):
            tile = Image.new('RGBA',(SIZE,SIZE),color)
            tile.alpha_composite(canvas)
            preview.paste(tile,(col*SIZE,row*SIZE))
    preview.convert('RGB').save(ASSETS/'preview.png')
    print('Packed three 128px transparent status icons; native HUD placement unchanged.')


if __name__ == '__main__':
    main()
